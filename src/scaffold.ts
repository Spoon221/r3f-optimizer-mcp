import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { PROFILES } from './profiles.js';

export interface ScaffoldOptions {
  root: string;
  dir?: string;
  typescript?: boolean;
  overwrite?: boolean;
}

/** Subset of profile values that make sense at runtime in the browser. */
function runtimeProfiles() {
  const pick = (id: keyof typeof PROFILES) => {
    const p = PROFILES[id];
    return {
      tier: p.id,
      dpr: [1, p.maxDpr],
      antialias: p.antialias,
      shadows: p.shadows,
      shadowMapSize: p.maxShadowMapSize,
      segments: p.maxSegments,
      postprocessing: p.postprocessing,
      physicalMaterials: p.physicalMaterials,
      maxTextureSize: p.maxTextureSize,
    };
  };
  return { low: pick('low'), mid: pick('mid'), high: pick('high') };
}

function deviceTierSource(ts: boolean): string {
  const T = (s: string) => (ts ? s : '');
  return `// Generated by r3f-optimizer-mcp. Device tier detection without external dependencies.

${ts ? `export type Tier = 'low' | 'mid' | 'high';\n\nexport type QualitySettings = (typeof QUALITY)[Tier];\n` : ''}
export const TIERS${T(': Tier[]')} = ['low', 'mid', 'high'];

export const QUALITY = ${JSON.stringify(runtimeProfiles(), null, 2)}${ts ? ' as const' : ''};

const LOW_END_GPU = /(mali-[4t]|adreno \\(tm\\) [3-5]\\d\\d|powervr|sgx|intel.*hd graphics [2-5]\\d{3}|swiftshader|llvmpipe|software)/i;
const HIGH_END_GPU = /(nvidia|geforce|rtx|radeon rx|apple m\\d|apple gpu)/i;

function gpuRenderer()${T(': string')} {
  try {
    const canvas = document.createElement('canvas');
    const gl = canvas.getContext('webgl2') || canvas.getContext('webgl');
    if (!gl) return '';
    const ext = gl.getExtension('WEBGL_debug_renderer_info');
    return String(ext ? gl.getParameter(ext.UNMASKED_RENDERER_WEBGL) : gl.getParameter(gl.RENDERER));
  } catch {
    return '';
  }
}

/** Explicit override: ?quality=low|mid|high or localStorage "quality". */
function overrideTier()${T(': Tier | null')} {
  try {
    const value = new URLSearchParams(window.location.search).get('quality') || localStorage.getItem('quality');
    return value && (TIERS${T(' as string[]')}).includes(value) ? (value${T(' as Tier')}) : null;
  } catch {
    return null;
  }
}

/**
 * Heuristic scoring of the device. Each signal adds points; the sum is mapped to a tier.
 * Signals: GPU renderer string, CPU cores, device memory, mobile form factor, screen pixels.
 */
export function detectTier()${T(': Tier')} {
  if (typeof window === 'undefined') return 'mid';
  const forced = overrideTier();
  if (forced) return forced;

  const nav = navigator${T(' as Navigator & { deviceMemory?: number }')};
  const renderer = gpuRenderer();
  const cores = nav.hardwareConcurrency || 4;
  const memory = nav.deviceMemory || 4;
  const mobile = /Android|iPhone|iPad|iPod|Mobile/i.test(nav.userAgent) || (nav.maxTouchPoints > 1 && window.innerWidth < 1024);
  const pixels = window.screen.width * window.screen.height * Math.pow(window.devicePixelRatio || 1, 2);

  let score = 0;
  if (LOW_END_GPU.test(renderer)) score -= 3;
  if (HIGH_END_GPU.test(renderer)) score += 3;
  score += cores >= 8 ? 1 : cores <= 4 ? -1 : 0;
  score += memory >= 8 ? 1 : memory <= 4 ? -1 : 0;
  if (mobile) score -= 1;
  if (pixels > 6_000_000) score -= 1;

  if (score <= -2) return 'low';
  if (score >= 2) return 'high';
  return 'mid';
}

export function lowerTier(tier${T(': Tier')})${T(': Tier')} {
  return tier === 'high' ? 'mid' : 'low';
}

/** "/models/robot.glb" -> "/models/robot.low.glb" (files produced by generate_asset_variants). */
export function modelUrl(url${T(': string')}, tier${T(': Tier')})${T(': string')} {
  return url.replace(/\\.(glb|gltf)$/i, \`.\${tier}.glb\`);
}
`;
}

function providerSource(ts: boolean): string {
  const T = (s: string) => (ts ? s : '');
  return `// Generated by r3f-optimizer-mcp. Quality context with automatic downgrade on low FPS.
import { createContext, useContext, useMemo, useState${T(', type ReactNode')} } from 'react';
import { PerformanceMonitor } from '@react-three/drei';
import { QUALITY, detectTier, lowerTier${T(', type QualitySettings, type Tier')} } from './deviceTier';

const QualityContext = createContext${T('<(QualitySettings & { setTier: (t: Tier) => void }) | null>')}(null);

/** Wrap the app (outside <Canvas>) to make the detected tier available everywhere. */
export function QualityProvider({ children, initialTier }${T(': { children: ReactNode; initialTier?: Tier }')}) {
  const [tier, setTier] = useState(() => initialTier || detectTier());
  const value = useMemo(() => ({ ...QUALITY[tier], setTier }), [tier]);
  return <QualityContext.Provider value={value}>{children}</QualityContext.Provider>;
}

export function useQuality() {
  const ctx = useContext(QualityContext);
  if (!ctx) throw new Error('useQuality() must be used inside <QualityProvider>');
  return ctx;
}

/**
 * Place inside <Canvas>. When the frame rate stays low the tier is lowered one step
 * (high -> mid -> low); it is never raised automatically to avoid oscillation.
 */
export function AdaptiveQuality({ children }${T(': { children?: ReactNode }')}) {
  const { tier, setTier } = useQuality();
  return (
    <PerformanceMonitor onDecline={() => setTier(lowerTier(tier))} flipflops={3}>
      {children}
    </PerformanceMonitor>
  );
}
`;
}

function usageSource(): string {
  return `// Example usage
import { Canvas } from '@react-three/fiber';
import { QualityProvider, AdaptiveQuality, useQuality } from './perf/QualityProvider';

function Scene() {
  const q = useQuality();
  return (
    <mesh castShadow={q.shadows}>
      <sphereGeometry args={[1, q.segments, q.segments]} />
      {q.physicalMaterials ? <meshPhysicalMaterial clearcoat={1} /> : <meshStandardMaterial />}
    </mesh>
  );
}

function App() {
  const q = useQuality();
  return (
    <Canvas dpr={q.dpr} shadows={q.shadows} gl={{ antialias: q.antialias }}>
      <AdaptiveQuality>
        <Scene />
      </AdaptiveQuality>
    </Canvas>
  );
}

export default function Root() {
  return (
    <QualityProvider>
      <App />
    </QualityProvider>
  );
}
`;
}

export async function scaffoldRuntime(options: ScaffoldOptions) {
  const dir = path.resolve(options.root, options.dir ?? 'src/perf');
  const ts = options.typescript ?? existsSync(path.join(options.root, 'tsconfig.json'));
  const files = [
    { name: ts ? 'deviceTier.ts' : 'deviceTier.js', content: deviceTierSource(ts) },
    { name: ts ? 'QualityProvider.tsx' : 'QualityProvider.jsx', content: providerSource(ts) },
  ];
  await mkdir(dir, { recursive: true });
  const written: string[] = [];
  const skipped: string[] = [];
  for (const f of files) {
    const target = path.join(dir, f.name);
    if (existsSync(target) && !options.overwrite) {
      skipped.push(target);
      continue;
    }
    await writeFile(target, f.content);
    written.push(target);
  }
  return {
    written,
    skipped,
    language: ts ? 'typescript' : 'javascript',
    peerDependencies: ['react', '@react-three/drei'],
    usage: usageSource(),
  };
}
